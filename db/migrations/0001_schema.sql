-- ======================= Row-level security (tenancy) ====================
-- Every tenant table shows and accepts only the current tenant's rows. FORCE
-- makes it apply to the owner (app_owner) too, i.e. inside api views/functions.
do $$
declare t text;
begin
  foreach t in array array[
    'attribute_types', 'rules', 'sites', 'buildings', 'blocks', 'floors', 'rooms',
    'beds', 'location_attributes', 'courses', 'course_attributes',
    'course_individual_attributes', 'allocations', 'audit_log']
  loop
    execute format('alter table core.%I enable row level security', t);
    execute format('alter table core.%I force row level security', t);
    execute format('create policy tenant_isolation on core.%I
                      using (tenant_id = core.current_tenant_id())
                      with check (tenant_id = core.current_tenant_id())', t);
  end loop;
end
$$;

