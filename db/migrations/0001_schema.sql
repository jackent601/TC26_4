-- 0001: core data model in the "core" schema, multi-tenant.
-- Applied by dbmate (runs inside one transaction). Nothing outside the "api"
-- schema is ever exposed to the API; see 0002.
--
-- Tenancy (decision D24):
--   * core.tenants lists the tenants (e.g. LIVE and DEMO). Every other table has
--     tenant_id, defaulting to the current tenant.
--   * The current tenant is the session setting app.tenant_id, set per request
--     through api.use_tenant(code). core.current_tenant_id() reads it.
--   * Row-level security on every tenant table shows and accepts only rows of
--     the current tenant. With no tenant set, nothing is visible.
--   * Links between tables include tenant_id (composite foreign keys), so a row
--     can never reference another tenant's row.
--   * All objects are owned by app_owner, a role that is NOT a superuser, and
--     row-level security is FORCEd, so it applies inside api views and
--     functions too (they run as app_owner). Superusers bypass it, so the
--     migration/admin login is never used by the application.
--------------------------------------------------------------------------------
do $$
begin
  if not exists (select from pg_roles where rolname = 'app_owner') then
    create role app_owner nologin;
  end if;
end
$$;

create schema core authorization app_owner;
set local role app_owner;    -- everything below is created and owned by app_owner

--------------------------------------------------------------------------------
-- Accommodation allocation MVP: v2 data model (14 tables + tenants)
-- Every object is created in the core schema (names are schema-qualified).
--
-- Tables, keys, relationships, checks and the tenant policies. No business logic.
-- Notes for porting:
--   * "generated by default as identity" works in PostgreSQL, Oracle 12c+ and DB2.
--   * Y/N flags are CHAR(1) with a check, since not every database has BOOLEAN.
--   * Dates: start = first night, end = departure day (exclusive), so two stays
--     overlap when a.start_date < b.end_date and b.start_date < a.end_date.
--   * Row-level security is PostgreSQL-specific (Oracle: Virtual Private Database).
--
-- Groups (as on the ER diagram):
--   Tenancy     tenants
--   Supply      sites > buildings > blocks > floors > rooms > beds,
--               location_attributes
--   Vocabulary  attribute_types, rules
--   Demand      courses, course_attributes, course_individual_attributes
--   Allocation  allocations
--   Audit       audit_log (standalone)
--------------------------------------------------------------------------------

-- =============================== Tenancy ================================

create table core.tenants (
  tenant_id integer generated by default as identity,
  code      varchar(30)  not null,
  name      varchar(100) not null,
  is_demo   char(1)      default 'N' not null,
  constraint tenants_pk primary key (tenant_id),
  constraint tenants_uk unique (code),
  constraint tenants_demo_ck check (is_demo in ('Y', 'N'))
);

-- The tenant for this session/transaction, or null when none is selected.
create function core.current_tenant_id() returns integer
language sql stable
as $$ select nullif(current_setting('app.tenant_id', true), '')::integer $$;

-- ============================== Vocabulary ==============================

-- Every attribute used on locations, courses or individuals.
-- inherit_mode: NEAREST = value set nearest the bed wins (a room can override its floor);
--               ANY     = applies if set at the bed or any level above; cannot be overridden.
-- allow_overlap / comment_required are enforced by application logic.
create table core.attribute_types (
  tenant_id integer default core.current_tenant_id() not null,
  attr_code        varchar(30)  not null,
  name             varchar(100) not null,
  description      varchar(400),
  applies_to       varchar(10)  not null,
  data_type        varchar(10)  default 'TEXT'    not null,
  inherit_mode     varchar(10)  default 'NEAREST' not null,
  allow_overlap    char(1)      default 'N'       not null,
  comment_required char(1)      default 'N'       not null,
  constraint attribute_types_pk primary key (tenant_id, attr_code),
  constraint attr_tenant_fk foreign key (tenant_id) references core.tenants (tenant_id),
  constraint attr_applies_ck  check (applies_to in ('LOCATION', 'INDIVIDUAL', 'BOTH')),
  constraint attr_datatype_ck check (data_type in ('TEXT', 'NUMBER', 'FLAG')),
  constraint attr_inherit_ck  check (inherit_mode in ('NEAREST', 'ANY')),
  constraint attr_overlap_ck  check (allow_overlap in ('Y', 'N')),
  constraint attr_comment_ck  check (comment_required in ('Y', 'N'))
);

-- Rules are data. Rule types:
--   COMPARE          individual attribute vs location attribute using operator
--   REQUIRES         individual flag Y needs location flag Y
--   MATCH_WITHIN     everyone within scope must share the individual attribute
--   SOLE_USE         individual flag Y should not share a room
--   LOCATION_BLOCKS  location flag Y blocks every allocation (e.g. OUT_OF_ACTION)
create table core.rules (
  tenant_id integer default core.current_tenant_id() not null,
  rule_code       varchar(30)  not null,
  name            varchar(200) not null,
  rule_type       varchar(20)  not null,
  individual_attr varchar(30),
  location_attr   varchar(30),
  operator        varchar(2),
  scope           varchar(10),
  severity        varchar(10)  default 'WARNING' not null,
  active          char(1)      default 'Y'       not null,
  message         varchar(400) not null,
  constraint rules_pk primary key (tenant_id, rule_code),
  constraint rules_tenant_fk   foreign key (tenant_id) references core.tenants (tenant_id),
  constraint rules_ind_attr_fk foreign key (tenant_id, individual_attr) references core.attribute_types (tenant_id, attr_code),
  constraint rules_loc_attr_fk foreign key (tenant_id, location_attr)   references core.attribute_types (tenant_id, attr_code),
  constraint rules_type_ck     check (rule_type in ('COMPARE', 'REQUIRES', 'MATCH_WITHIN', 'SOLE_USE', 'LOCATION_BLOCKS')),
  constraint rules_operator_ck check (operator in ('>=', '<=', '=')),
  constraint rules_scope_ck    check (scope in ('ROOM', 'FLOOR', 'BLOCK')),
  constraint rules_severity_ck check (severity in ('BLOCK', 'WARNING', 'INFO')),
  constraint rules_active_ck   check (active in ('Y', 'N')),
  -- Which attributes each rule type needs
  constraint rules_attrs_ck check (
       (rule_type = 'LOCATION_BLOCKS' and individual_attr is null and location_attr is not null)
    or (rule_type in ('COMPARE', 'REQUIRES') and individual_attr is not null and location_attr is not null)
    or (rule_type in ('MATCH_WITHIN', 'SOLE_USE') and individual_attr is not null))
);

