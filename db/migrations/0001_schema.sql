-- Accommodation allocation MVP: v2 data model (14 tables)
-- Every object is created in the core schema (names are schema-qualified).
--
-- Structure only: tables, keys, relationships and checks. No triggers, views or data.
-- Written in standard SQL so it is not tied to one database. Notes for porting:
--   * "generated by default as identity" works in PostgreSQL, Oracle 12c+ and DB2.
--     SQL Server: use IDENTITY(1,1). MySQL: use AUTO_INCREMENT. SQLite: INTEGER PRIMARY KEY.
--   * Y/N flags are CHAR(1) with a check, since not every database has BOOLEAN.
--   * Dates: start = first night, end = departure day (exclusive), so two stays
--     overlap when a.start_date < b.end_date and b.start_date < a.end_date.
--
-- Groups (as on the ER diagram):
--   Supply      sites > buildings > blocks > floors > rooms > beds,
--               location_attributes
--   Vocabulary  attribute_types, rules
--   Demand      courses, course_attributes, course_individual_attributes
--   Allocation  allocations
--   Audit       audit_log (standalone)
--------------------------------------------------------------------------------

-- ============================== Vocabulary ==============================

-- Every attribute used on locations, courses or individuals.
-- inherit_mode: NEAREST = value set nearest the bed wins (a room can override its floor);
--               ANY     = applies if set at the bed or any level above; cannot be overridden.
-- allow_overlap / comment_required are enforced by application logic.
create table core.attribute_types (
  attr_code        varchar(30)  not null,
  name             varchar(100) not null,
  description      varchar(400),
  applies_to       varchar(10)  not null,
  data_type        varchar(10)  default 'TEXT'    not null,
  inherit_mode     varchar(10)  default 'NEAREST' not null,
  allow_overlap    char(1)      default 'N'       not null,
  comment_required char(1)      default 'N'       not null,
  constraint attribute_types_pk primary key (attr_code),
  constraint attr_applies_ck  check (applies_to in ('LOCATION', 'INDIVIDUAL', 'BOTH')),
  constraint attr_datatype_ck check (data_type in ('TEXT', 'NUMBER', 'FLAG')),
  constraint attr_inherit_ck  check (inherit_mode in ('NEAREST', 'ANY')),
  constraint attr_overlap_ck  check (allow_overlap in ('Y', 'N')),
  constraint attr_comment_ck  check (comment_required in ('Y', 'N'))
);

-- Rules are data. Rule types:
--   COMPARE          individual attribute vs location attribute using operator
--   REQUIRES         individual flag Y needs location flag Y
--   MATCH_WITHIN     everyone within scope must share the individual attribute
--   SOLE_USE         individual flag Y should not share a room
--   LOCATION_BLOCKS  location flag Y blocks every allocation (e.g. OUT_OF_ACTION)
create table core.rules (
  rule_code       varchar(30)  not null,
  name            varchar(200) not null,
  rule_type       varchar(20)  not null,
  individual_attr varchar(30),
  location_attr   varchar(30),
  operator        varchar(2),
  scope           varchar(10),
  severity        varchar(10)  default 'WARNING' not null,
  active          char(1)      default 'Y'       not null,
  message         varchar(400) not null,
  constraint rules_pk primary key (rule_code),
  constraint rules_ind_attr_fk foreign key (individual_attr) references core.attribute_types (attr_code),
  constraint rules_loc_attr_fk foreign key (location_attr)   references core.attribute_types (attr_code),
  constraint rules_type_ck     check (rule_type in ('COMPARE', 'REQUIRES', 'MATCH_WITHIN', 'SOLE_USE', 'LOCATION_BLOCKS')),
  constraint rules_operator_ck check (operator in ('>=', '<=', '=')),
  constraint rules_scope_ck    check (scope in ('ROOM', 'FLOOR', 'BLOCK')),
  constraint rules_severity_ck check (severity in ('BLOCK', 'WARNING', 'INFO')),
  constraint rules_active_ck   check (active in ('Y', 'N')),
  -- Which attributes each rule type needs
  constraint rules_attrs_ck check (
       (rule_type = 'LOCATION_BLOCKS' and individual_attr is null and location_attr is not null)
    or (rule_type in ('COMPARE', 'REQUIRES') and individual_attr is not null and location_attr is not null)
    or (rule_type in ('MATCH_WITHIN', 'SOLE_USE') and individual_attr is not null))
);

-- ================================ Supply ================================

create table core.sites (
  site_id    integer generated by default as identity,
  code       varchar(30)  not null,
  name       varchar(100) not null,
  sort_order integer      default 0 not null,
  constraint sites_pk primary key (site_id),
  constraint sites_uk unique (code)
);

create table core.buildings (
  building_id integer generated by default as identity,
  site_id     integer      not null,
  code        varchar(30)  not null,
  name        varchar(100) not null,
  sort_order  integer      default 0 not null,
  constraint buildings_pk primary key (building_id),
  constraint buildings_site_fk foreign key (site_id) references core.sites (site_id),
  constraint buildings_uk unique (site_id, code)
);

create table core.blocks (
  block_id    integer generated by default as identity,
  building_id integer      not null,
  code        varchar(30)  not null,
  name        varchar(100) not null,
  sort_order  integer      default 0 not null,
  constraint blocks_pk primary key (block_id),
  constraint blocks_building_fk foreign key (building_id) references core.buildings (building_id),
  constraint blocks_uk unique (building_id, code)
);

create table core.floors (
  floor_id   integer generated by default as identity,
  block_id   integer      not null,
  code       varchar(30)  not null,
  name       varchar(100) not null,
  sort_order integer      default 0 not null,
  constraint floors_pk primary key (floor_id),
  constraint floors_block_fk foreign key (block_id) references core.blocks (block_id),
  constraint floors_uk unique (block_id, code)
);

create table core.rooms (
  room_id    integer generated by default as identity,
  floor_id   integer      not null,
  code       varchar(30)  not null,
  name       varchar(100) not null,
  sort_order integer      default 0 not null,
  constraint rooms_pk primary key (room_id),
  constraint rooms_floor_fk foreign key (floor_id) references core.floors (floor_id),
  constraint rooms_uk unique (floor_id, code)
);

create table core.beds (
  bed_id  integer generated by default as identity,
  room_id integer     not null,
  code    varchar(30) not null,
  constraint beds_pk primary key (bed_id),
  constraint beds_room_fk foreign key (room_id) references core.rooms (room_id),
  constraint beds_uk unique (room_id, code)
);

-- An attribute set at exactly one level of the estate, for a date range.
-- Outages are rows here: attr_code OUT_OF_ACTION, value Y, reason in comments.
create table core.location_attributes (
  loc_attr_id integer generated by default as identity,
  attr_code   varchar(30)  not null,
  attr_value  varchar(100) not null,
  valid_from  date         default date '2000-01-01' not null,
  valid_to    date         default date '9999-12-31' not null,  -- exclusive
  comments    varchar(1000),
  site_id     integer,
  building_id integer,
  block_id    integer,
  floor_id    integer,
  room_id     integer,
  bed_id      integer,
  constraint loc_attr_pk primary key (loc_attr_id),
  constraint loc_attr_type_fk     foreign key (attr_code)   references core.attribute_types (attr_code),
  constraint loc_attr_site_fk     foreign key (site_id)     references core.sites (site_id)         on delete cascade,
  constraint loc_attr_building_fk foreign key (building_id) references core.buildings (building_id) on delete cascade,
  constraint loc_attr_block_fk    foreign key (block_id)    references core.blocks (block_id)       on delete cascade,
  constraint loc_attr_floor_fk    foreign key (floor_id)    references core.floors (floor_id)       on delete cascade,
  constraint loc_attr_room_fk     foreign key (room_id)     references core.rooms (room_id)         on delete cascade,
  constraint loc_attr_bed_fk      foreign key (bed_id)      references core.beds (bed_id)           on delete cascade,
  constraint loc_attr_dates_ck check (valid_to > valid_from),
  -- Exactly one level is set
  constraint loc_attr_level_ck check (
      (case when site_id     is not null then 1 else 0 end)
    + (case when building_id is not null then 1 else 0 end)
    + (case when block_id    is not null then 1 else 0 end)
    + (case when floor_id    is not null then 1 else 0 end)
    + (case when room_id     is not null then 1 else 0 end)
    + (case when bed_id      is not null then 1 else 0 end) = 1)
);

-- ================================ Demand ================================

-- scheduled = planned number of attendees (set when the course is requested)
-- loaded    = attendees actually registered; updated as registrations come in
-- Anonymous individuals are numbered 1..greatest(scheduled, loaded)
create table core.courses (
  course_id     integer generated by default as identity,
  code          varchar(30)  not null,
  name          varchar(200) not null,
  site_id       integer,
  start_date    date         not null,
  end_date      date         not null,
  scheduled     integer      default 0 not null,
  loaded        integer      default 0 not null,
  loaded_at     timestamp,
  status        varchar(12)  default 'REQUESTED' not null,
  notes         varchar(4000),
  constraint courses_pk primary key (course_id),
  constraint courses_uk unique (code),
  constraint courses_site_fk foreign key (site_id) references core.sites (site_id),
  constraint courses_dates_ck  check (end_date > start_date),
  constraint courses_sched_ck  check (scheduled >= 0),
  constraint courses_loaded_ck check (loaded >= 0),
  constraint courses_status_ck check (status in ('REQUESTED', 'CONFIRMED', 'CANCELLED'))
);

-- Default attribute values for every individual on the course
create table core.course_attributes (
  course_id  integer      not null,
  attr_code  varchar(30)  not null,
  attr_value varchar(100) not null,
  constraint course_attr_pk primary key (course_id, attr_code),
  constraint course_attr_course_fk foreign key (course_id) references core.courses (course_id) on delete cascade,
  constraint course_attr_type_fk   foreign key (attr_code) references core.attribute_types (attr_code)
);

-- One anonymous individual's attribute on a course; overrides the course default.
-- No row needed for an individual who only has the course defaults.
create table core.course_individual_attributes (
  course_id     integer      not null,
  individual_no integer      not null,
  attr_code     varchar(30)  not null,
  attr_value    varchar(100) not null,
  constraint course_ind_attr_pk primary key (course_id, individual_no, attr_code),
  constraint course_ind_attr_course_fk foreign key (course_id) references core.courses (course_id) on delete cascade,
  constraint course_ind_attr_type_fk   foreign key (attr_code) references core.attribute_types (attr_code),
  constraint course_ind_attr_no_ck check (individual_no >= 1)
);

-- ============================== Allocation ==============================

-- An individual on a course (or an external booking) in a bed for a range of nights.
-- Also the booking itself: carries the stay status and check-in/out.
-- individual_no is not a foreign key: individuals have no table of their own.
-- It should be between 1 and greatest(scheduled, loaded) for the course (application logic).
create table core.allocations (
  allocation_id  integer generated by default as identity,
  course_id      integer,
  individual_no  integer,
  bed_id         integer      not null,
  start_date     date         not null,
  end_date       date         not null,
  status         varchar(12)  default 'ALLOCATED' not null,
  checked_in_at  timestamp,
  checked_out_at timestamp,
  source         varchar(10)  default 'LOCAL' not null,
  external_ref   varchar(50),
  external_name  varchar(200),
  created_at     timestamp    default current_timestamp not null,
  constraint alloc_pk primary key (allocation_id),
  constraint alloc_course_fk foreign key (course_id) references core.courses (course_id) on delete cascade,
  constraint alloc_bed_fk    foreign key (bed_id)    references core.beds (bed_id),
  constraint alloc_dates_ck  check (end_date > start_date),
  constraint alloc_no_ck     check (individual_no >= 1),
  constraint alloc_status_ck check (status in ('ALLOCATED', 'BOOKED', 'CHECKED_IN', 'CHECKED_OUT', 'NO_SHOW', 'CANCELLED')),
  constraint alloc_source_ck check (source in ('LOCAL', 'EXTERNAL')),
  -- A course allocation names its individual; an external booking has neither
  constraint alloc_owner_ck check (
       (course_id is not null and individual_no is not null)
    or (course_id is null and individual_no is null and source = 'EXTERNAL')),
  -- Check-in/out times only once the status has got there
  constraint alloc_checkin_ck check (
       (status in ('CHECKED_IN', 'CHECKED_OUT') or checked_in_at is null)
   and (status = 'CHECKED_OUT' or checked_out_at is null))
);

-- ================================= Audit ================================

-- Standalone history: no foreign keys, so entries survive deletes.
-- course_id + individual_no are kept only to look up one individual's history.
create table core.audit_log (
  audit_id      integer generated by default as identity,
  table_name    varchar(30)   not null,
  record_id     integer       not null,
  course_id     integer,
  individual_no integer,
  action        varchar(10)   not null,
  detail        varchar(4000),
  changed_by    varchar(100)  not null,
  changed_at    timestamp     default current_timestamp not null,
  constraint audit_log_pk primary key (audit_id)
);

