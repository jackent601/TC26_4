-- An attribute set at exactly one level of the estate, for a date range.
-- Outages are rows here: attr_code OUT_OF_ACTION, value Y, reason in comments.
create table core.location_attributes (
  tenant_id integer default core.current_tenant_id() not null,
  loc_attr_id integer generated by default as identity,
  attr_code   varchar(30)  not null,
  attr_value  varchar(100) not null,
  valid_from  date         default date '2000-01-01' not null,
  valid_to    date         default date '9999-12-31' not null,  -- exclusive
  comments    varchar(1000),
  site_id     integer,
  building_id integer,
  block_id    integer,
  floor_id    integer,
  room_id     integer,
  bed_id      integer,
  constraint loc_attr_pk primary key (loc_attr_id),
  constraint loc_attr_type_fk     foreign key (tenant_id, attr_code)   references core.attribute_types (tenant_id, attr_code),
  constraint loc_attr_site_fk     foreign key (tenant_id, site_id)     references core.sites (tenant_id, site_id)         on delete cascade,
  constraint loc_attr_building_fk foreign key (tenant_id, building_id) references core.buildings (tenant_id, building_id) on delete cascade,
  constraint loc_attr_block_fk    foreign key (tenant_id, block_id)    references core.blocks (tenant_id, block_id)       on delete cascade,
  constraint loc_attr_floor_fk    foreign key (tenant_id, floor_id)    references core.floors (tenant_id, floor_id)       on delete cascade,
  constraint loc_attr_room_fk     foreign key (tenant_id, room_id)     references core.rooms (tenant_id, room_id)         on delete cascade,
  constraint loc_attr_bed_fk      foreign key (tenant_id, bed_id)      references core.beds (tenant_id, bed_id)           on delete cascade,
  constraint loc_attr_dates_ck check (valid_to > valid_from),
  -- Exactly one level is set
  constraint loc_attr_level_ck check (
      (case when site_id     is not null then 1 else 0 end)
    + (case when building_id is not null then 1 else 0 end)
    + (case when block_id    is not null then 1 else 0 end)
    + (case when floor_id    is not null then 1 else 0 end)
    + (case when room_id     is not null then 1 else 0 end)
    + (case when bed_id      is not null then 1 else 0 end) = 1)
);

-- ================================ Demand ================================

-- scheduled = planned number of attendees (set when the course is requested)
-- loaded    = attendees actually registered; updated as registrations come in
-- Anonymous individuals are numbered 1..greatest(scheduled, loaded)
create table core.courses (
  tenant_id integer default core.current_tenant_id() not null,
  course_id     integer generated by default as identity,
  code          varchar(30)  not null,
  name          varchar(200) not null,
  site_id       integer,
  start_date    date         not null,
  end_date      date         not null,
  scheduled     integer      default 0 not null,
  loaded        integer      default 0 not null,
  loaded_at     timestamp,
  status        varchar(12)  default 'REQUESTED' not null,
  notes         varchar(4000),
  constraint courses_pk primary key (course_id),
  constraint courses_tenant_uk unique (tenant_id, course_id),
  constraint courses_tenant_fk foreign key (tenant_id) references core.tenants (tenant_id),
  constraint courses_uk unique (tenant_id, code),
  constraint courses_site_fk foreign key (tenant_id, site_id) references core.sites (tenant_id, site_id),
  constraint courses_dates_ck  check (end_date > start_date),
  constraint courses_sched_ck  check (scheduled >= 0),
  constraint courses_loaded_ck check (loaded >= 0),
  constraint courses_status_ck check (status in ('REQUESTED', 'CONFIRMED', 'CANCELLED'))
);

-- Default attribute values for every individual on the course
create table core.course_attributes (
  tenant_id integer default core.current_tenant_id() not null,
  course_id  integer      not null,
  attr_code  varchar(30)  not null,
  attr_value varchar(100) not null,
  constraint course_attr_pk primary key (course_id, attr_code),
  constraint course_attr_course_fk foreign key (tenant_id, course_id) references core.courses (tenant_id, course_id) on delete cascade,
  constraint course_attr_type_fk   foreign key (tenant_id, attr_code) references core.attribute_types (tenant_id, attr_code)
);

-- One anonymous individual's attribute on a course; overrides the course default.
-- No row needed for an individual who only has the course defaults.
create table core.course_individual_attributes (
  tenant_id integer default core.current_tenant_id() not null,
  course_id     integer      not null,
  individual_no integer      not null,
  attr_code     varchar(30)  not null,
  attr_value    varchar(100) not null,
  constraint course_ind_attr_pk primary key (course_id, individual_no, attr_code),
  constraint course_ind_attr_course_fk foreign key (tenant_id, course_id) references core.courses (tenant_id, course_id) on delete cascade,
  constraint course_ind_attr_type_fk   foreign key (tenant_id, attr_code) references core.attribute_types (tenant_id, attr_code),
  constraint course_ind_attr_no_ck check (individual_no >= 1)
);

-- ============================== Allocation ==============================

-- An individual on a course (or an external booking) in a bed for a range of nights.
-- Also the booking itself: carries the stay status and check-in/out.
-- individual_no is not a foreign key: individuals have no table of their own.
-- It should be between 1 and greatest(scheduled, loaded) for the course (application logic).
create table core.allocations (
  tenant_id integer default core.current_tenant_id() not null,
  allocation_id  integer generated by default as identity,
  course_id      integer,
  individual_no  integer,
  bed_id         integer      not null,
  start_date     date         not null,
  end_date       date         not null,
  status         varchar(12)  default 'ALLOCATED' not null,
  checked_in_at  timestamp,
  checked_out_at timestamp,
  source         varchar(10)  default 'LOCAL' not null,
  external_ref   varchar(50),
  external_name  varchar(200),
  created_at     timestamp    default current_timestamp not null,
  constraint alloc_pk primary key (allocation_id),
  constraint alloc_tenant_fk foreign key (tenant_id) references core.tenants (tenant_id),
  constraint alloc_course_fk foreign key (tenant_id, course_id) references core.courses (tenant_id, course_id) on delete cascade,
  constraint alloc_bed_fk    foreign key (tenant_id, bed_id)    references core.beds (tenant_id, bed_id),
  constraint alloc_dates_ck  check (end_date > start_date),
  constraint alloc_no_ck     check (individual_no >= 1),
  constraint alloc_status_ck check (status in ('ALLOCATED', 'BOOKED', 'CHECKED_IN', 'CHECKED_OUT', 'NO_SHOW', 'CANCELLED')),
  constraint alloc_source_ck check (source in ('LOCAL', 'EXTERNAL')),
  -- A course allocation names its individual; an external booking has neither
  constraint alloc_owner_ck check (
       (course_id is not null and individual_no is not null)
    or (course_id is null and individual_no is null and source = 'EXTERNAL')),
  -- Check-in/out times only once the status has got there
  constraint alloc_checkin_ck check (
       (status in ('CHECKED_IN', 'CHECKED_OUT') or checked_in_at is null)
   and (status = 'CHECKED_OUT' or checked_out_at is null))
);

-- ================================= Audit ================================

